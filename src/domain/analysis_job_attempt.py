"""Inactive, immutable worker ownership and claim values; no persistence or execution."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timedelta
from enum import StrEnum
from typing import Final
from uuid import UUID

from domain.analysis_job import (
    _validate_datetime,
    _validate_request_text,
    _validate_uuid,
    _validate_video_integrity,
)
from domain.video_integrity import VideoIntegrity

__all__ = [
    "AttemptAuthority",
    "AttemptFailureCode",
    "AttemptStatus",
    "ClaimableAnalysisJob",
    "LeaseDuration",
    "LeaseId",
    "RecoveryBatchSize",
    "WorkerClaim",
    "WorkerSlotId",
]

_FAILURE_CODE: Final = re.compile(r"[a-z][a-z0-9_]{0,63}")
_ANALYSIS_VERSION: Final = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}")


class AttemptStatus(StrEnum):
    """Exact durable attempt-status vocabulary."""

    ACTIVE = "ACTIVE"
    INTERRUPTED = "INTERRUPTED"
    RETRYABLE_FAILURE = "RETRYABLE_FAILURE"
    TERMINAL_FAILURE = "TERMINAL_FAILURE"
    EXHAUSTED = "EXHAUSTED"
    SUCCEEDED = "SUCCEEDED"


@dataclass(frozen=True, slots=True)
class WorkerSlotId:
    """Identity of one execution-slot incarnation, not one claim."""

    value: UUID

    def __post_init__(self) -> None:
        _validate_uuid(self.value)


@dataclass(frozen=True, slots=True)
class LeaseId:
    """Opaque identity supplied for one claim; never generated by a value."""

    value: UUID

    def __post_init__(self) -> None:
        _validate_uuid(self.value)


@dataclass(frozen=True, slots=True)
class LeaseDuration:
    value: timedelta

    def __post_init__(self) -> None:
        if type(self.value) is not timedelta:
            raise TypeError("Lease duration must be an exact timedelta.")
        if self.value <= timedelta(0):
            raise ValueError("Lease duration must be positive.")


@dataclass(frozen=True, slots=True)
class RecoveryBatchSize:
    value: int

    def __post_init__(self) -> None:
        _validate_positive_int(self.value)


@dataclass(frozen=True, slots=True)
class AttemptFailureCode:
    value: str

    def __post_init__(self) -> None:
        if type(self.value) is not str:
            raise TypeError("Admission identifiers must be strings.")
        if not _FAILURE_CODE.fullmatch(self.value):
            raise ValueError("Failure code must have bounded safe syntax.")


@dataclass(frozen=True, slots=True)
class AttemptAuthority:
    """The complete supplied job/generation/slot/lease fencing tuple."""

    job_id: UUID
    attempt_number: int
    worker_slot_id: WorkerSlotId
    lease_id: LeaseId

    def __post_init__(self) -> None:
        _validate_uuid(self.job_id)
        _validate_positive_int(self.attempt_number)
        if not isinstance(self.worker_slot_id, WorkerSlotId):
            raise TypeError("Worker slot must be a WorkerSlotId.")
        if not isinstance(self.lease_id, LeaseId):
            raise TypeError("Lease must be a LeaseId.")


@dataclass(frozen=True, slots=True)
class ClaimableAnalysisJob:
    """Immutable execution inputs, with no protected lookup or runtime resources."""

    job_id: UUID
    video_id: str
    player_id: str
    video_reference: str
    callback_url: str
    analysis_version: str
    attempt_limit: int
    accepted_at: datetime
    video_integrity: VideoIntegrity | None = None

    def __post_init__(self) -> None:
        _validate_uuid(self.job_id)
        _validate_request_text(
            self.video_id, self.player_id, self.video_reference, self.callback_url
        )
        if type(self.analysis_version) is not str:
            raise TypeError("Admission identifiers must be strings.")
        if not _ANALYSIS_VERSION.fullmatch(self.analysis_version):
            raise ValueError("Analysis version must have bounded safe syntax.")
        _validate_positive_int(self.attempt_limit)
        _validate_datetime(self.accepted_at)
        _validate_video_integrity(self.video_integrity)


@dataclass(frozen=True, slots=True)
class WorkerClaim:
    authority: AttemptAuthority
    job: ClaimableAnalysisJob
    started_at: datetime
    heartbeat_at: datetime
    lease_expires_at: datetime

    def __post_init__(self) -> None:
        _validate_authority(self.authority)
        if not isinstance(self.job, ClaimableAnalysisJob):
            raise TypeError("Claim job must be a ClaimableAnalysisJob.")
        _validate_datetime(self.started_at)
        _validate_datetime(self.heartbeat_at)
        _validate_datetime(self.lease_expires_at)
        if _instant_key(self.heartbeat_at) < _instant_key(self.started_at):
            raise ValueError("Heartbeat must not precede attempt start.")
        if _instant_key(self.lease_expires_at) <= _instant_key(self.heartbeat_at):
            raise ValueError("Lease expiry must follow heartbeat.")


def _instant_key(value: datetime) -> timedelta:
    """Compare aware instants without fold semantics or UTC datetime overflow."""
    offset = value.utcoffset()
    if offset is None:
        raise ValueError("Timestamp must have a valid timezone offset.")
    return (value.replace(tzinfo=None) - datetime.min) - offset


def _validate_positive_int(value: int) -> None:
    if type(value) is not int:
        raise TypeError("Policy value must be an exact integer.")
    if value <= 0:
        raise ValueError("Policy value must be positive.")


def _validate_authority(value: AttemptAuthority) -> None:
    if not isinstance(value, AttemptAuthority):
        raise TypeError("Authority must be an AttemptAuthority.")


def _validate_failure_code(value: AttemptFailureCode) -> None:
    if not isinstance(value, AttemptFailureCode):
        raise TypeError("Failure code must be an AttemptFailureCode.")
